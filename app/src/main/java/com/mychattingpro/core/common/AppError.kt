package com.mychattingpro.core.common

import android.content.Context
import com.example.R

sealed class AppError {
    data object InvalidPhone : AppError()
    data object InvalidPin : AppError()
    data object PinMismatch : AppError()
    data object WrongPin : AppError()
    data object AccountNotFound : AppError()
    data object DuplicateAccount : AppError()
    data class RateLimited(val retryAfterSeconds: Int) : AppError()
    data object NetworkUnavailable : AppError()
    data object TimeoutError : AppError()
    data object StorageFailure : AppError()
    data object StoragePermissionDenied : AppError()
    data object StorageBucketMissing : AppError()
    data object UnsupportedMediaType : AppError()
    data object EmptyMediaFile : AppError()
    data class MediaTooLarge(val maxMb: Int) : AppError()
    data object CallFailure : AppError()
    data object InvalidOwnerKey : AppError()
    data object OwnerAccessDenied : AppError()
    data object OwnerMonitorNotConfigured : AppError()
    data object WrongPrivatePin : AppError()
    data class PrivatePinLocked(val retryAfterSeconds: Int) : AppError()
    data object PrivatePinNotSet : AppError()
    data object PrivatePinAlreadySet : AppError()
    data object PrivateChatLocked : AppError()
    data object SimRequired : AppError()
    data object SimPermissionRequired : AppError()
    data object SimNumberMismatch : AppError()
    data object SelfSearchNotAllowed : AppError()
    data object InvalidRecoveryCode : AppError()
    data object RecoveryCodeNotSet : AppError()
    data object InvalidDeleteConfirmation : AppError()
    data object DuplicateReport : AppError()
    data object SessionRevoked : AppError()
    data object UserBlocked : AppError()
    data object ConversationInPrivateChat : AppError()
    data object CannotMoveNativePrivateChat : AppError()
    data class ServerError(val serverMessage: String? = null) : AppError()

    fun toLocalizedMessage(context: Context): String = when (this) {
        InvalidPhone -> context.getString(R.string.err_invalid_phone)
        InvalidPin -> context.getString(R.string.err_invalid_pin)
        PinMismatch -> context.getString(R.string.err_pin_mismatch)
        WrongPin -> context.getString(R.string.err_wrong_pin)
        AccountNotFound -> context.getString(R.string.err_account_not_found)
        DuplicateAccount -> context.getString(R.string.err_duplicate_account)
        is RateLimited -> context.getString(R.string.err_rate_limit, retryAfterSeconds.coerceAtLeast(1))
        NetworkUnavailable -> context.getString(R.string.err_network)
        TimeoutError -> context.getString(R.string.err_timeout)
        StorageFailure -> context.getString(R.string.err_storage)
        StoragePermissionDenied -> context.getString(R.string.err_storage_permission_denied)
        StorageBucketMissing -> context.getString(R.string.err_storage_bucket_missing)
        UnsupportedMediaType -> context.getString(R.string.err_unsupported_media_type)
        EmptyMediaFile -> context.getString(R.string.err_empty_media_file)
        is MediaTooLarge -> context.getString(R.string.err_media_too_large, maxMb)
        CallFailure -> context.getString(R.string.err_call)
        InvalidOwnerKey -> context.getString(R.string.err_invalid_owner_key)
        OwnerAccessDenied -> context.getString(R.string.err_owner_access_denied)
        OwnerMonitorNotConfigured -> context.getString(R.string.err_owner_not_configured)
        WrongPrivatePin -> context.getString(R.string.err_wrong_private_pin)
        is PrivatePinLocked -> context.getString(R.string.err_private_pin_locked, retryAfterSeconds.coerceAtLeast(1))
        PrivatePinNotSet -> context.getString(R.string.err_private_pin_not_set)
        PrivatePinAlreadySet -> context.getString(R.string.err_private_pin_already_set)
        PrivateChatLocked -> context.getString(R.string.err_private_chat_locked)
        SimRequired -> context.getString(R.string.err_sim_required)
        SimPermissionRequired -> context.getString(R.string.err_sim_permission_required)
        SimNumberMismatch -> context.getString(R.string.err_sim_number_mismatch)
        SelfSearchNotAllowed -> context.getString(R.string.err_self_search)
        InvalidRecoveryCode -> context.getString(R.string.err_invalid_recovery_code)
        RecoveryCodeNotSet -> context.getString(R.string.err_recovery_code_not_set)
        InvalidDeleteConfirmation -> context.getString(R.string.err_invalid_delete_confirmation)
        DuplicateReport -> context.getString(R.string.err_duplicate_report)
        SessionRevoked -> context.getString(R.string.err_session_revoked)
        UserBlocked -> context.getString(R.string.err_user_blocked)
        ConversationInPrivateChat -> context.getString(R.string.err_conversation_in_private_chat)
        CannotMoveNativePrivateChat -> context.getString(R.string.err_cannot_move_native_private_chat)
        is ServerError -> serverMessage?.takeIf { it.isNotBlank() } ?: context.getString(R.string.err_server)
    }
}
